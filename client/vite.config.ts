/// <reference types="vitest/config" />
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin, type ProxyOptions } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * Preloads the Latin body and display fonts so they arrive alongside the JavaScript. Without
 * this, text first renders in the fallback font and reflows when the web font loads (layout shift).
 */
function preloadFonts(): Plugin {
  return {
    name: 'aaroh-preload-fonts',
    apply: 'build',
    transformIndexHtml(_html, ctx) {
      const fonts = Object.keys(ctx.bundle ?? {}).filter((file) =>
        /\/(inter(-tight)?-latin-wght-normal|instrument-serif-latin-400-(italic|normal))-[\w-]+\.woff2$/.test(
          file,
        ),
      );
      return fonts.map((file) => ({
        tag: 'link',
        attrs: {
          rel: 'preload',
          href: `/${file}`,
          as: 'font',
          type: 'font/woff2',
          crossorigin: '',
        },
        injectTo: 'head-prepend',
      }));
    },
  };
}

// The brand icon beside the name in the header (see <BrandIcon />). Its dots are read from
// public/brand/icon.svg (generated by aaroh-logo/scripts/build.mjs) at build time (and when the
// dev server starts) so the page can draw and animate each one.
function readBrandIcon() {
  const file = fileURLToPath(new URL('./public/brand/icon.svg', import.meta.url));
  if (!existsSync(file)) return null;
  const svg = readFileSync(file, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) return null;
  const [, top = 0, , height = 0] = viewBox.split(' ').map(Number);
  const dots = [...svg.matchAll(/<circle([^>]*)\/>/g)].map(([, attrs = '']) => {
    const attr = (name: string) => Number(new RegExp(` ${name}="([^"]+)"`).exec(attrs)?.[1]);
    // The gold dot carries its own fill; the others take the text colour.
    const fill = /style="fill:([^"]+)"/.exec(attrs)?.[1] ?? 'currentColor';
    return { cx: attr('cx'), cy: attr('cy'), r: attr('r'), fill };
  });
  if (dots.length === 0) return null;
  dots.sort((a, b) => a.cx - b.cx);
  // Where each dot goes when the icon lies flat: one level row through the middle, evenly
  // spaced (FLAT_GAP between neighbours), starting where the first dot starts.
  const FLAT_GAP = 3.5;
  let x = (dots[0]?.cx ?? 0) - (dots[0]?.r ?? 0);
  const middle = top + height / 2;
  return {
    viewBox,
    dots: dots.map((dot) => {
      const flat = { x: x + dot.r, y: middle };
      x += 2 * dot.r + FLAT_GAP;
      return { ...dot, flat };
    }),
  };
}

// Requests for data, media and SEO files go to the Express server in development.
const API_SERVER = 'http://localhost:4000';
let lastHint = 0;
const toApiServer: ProxyOptions = {
  target: API_SERVER,
  configure: (proxy) => {
    proxy.on('error', (err: NodeJS.ErrnoException) => {
      // The usual cause: only the client was started (e.g. `npm run dev` inside client/).
      if (!/ECONNREFUSED/.test(`${err.code} ${err.message}`) || Date.now() - lastHint < 10_000)
        return;
      lastHint = Date.now();
      console.warn(
        `\n  The API server is not running on ${API_SERVER}.\n` +
          '  Start the whole site from the repository root:  npm run dev\n',
      );
    });
  },
};

export default defineConfig({
  plugins: [react(), preloadFonts()],
  define: {
    __BRAND_ICON__: JSON.stringify(readBrandIcon()),
  },
  server: {
    port: 5173,
    proxy: {
      '/api': toApiServer,
      '/media': toApiServer,
      '/sitemap.xml': toApiServer,
      '/robots.txt': toApiServer,
    },
  },
  build: {
    outDir: 'dist',
    sourcemap: true,
    // The server reads .vite/manifest.json to preload each page's code (server/src/seo).
    manifest: true,
  },
  test: {
    include: ['src/**/*.test.ts'],
  },
});
